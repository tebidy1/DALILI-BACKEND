import { describe, expect, it } from 'vitest'
import { werDetail } from './wer'

/** بوابة VOX-04: WER ‏≤20% — المنطق نقِي في core ليُعاد استخدامه على أدلة المالك الحقيقية */
describe('wer — نسبة أخطاء الكلمات', () => {
  it('نص مطابق تمامًا → صفر', () => {
    expect(werDetail('افتح صفحة الفواتير واضغط إنشاء', 'افتح صفحة الفواتير واضغط إنشاء').wer).toBe(0)
  })

  it('إبدال كلمة واحدة من عشر → 0.1', () => {
    expect(werDetail('واحد اثنان ثلاثة أربعة خمسة ستة سبعة ثمانية تسعة عشرة', 'واحد اثنان ثلاثة خمسة خمسة ستة سبعة ثمانية تسعة عشرة').wer).toBeCloseTo(0.1, 10)
  })

  it('التشكيل والهمزات وة/ه وى/ي لا تُحتسب أخطاء', () => {
    expect(werDetail('افتَح صَفحَة الفواتير', 'افتح صفحه الفواتير').wer).toBe(0)
    expect(werDetail('إلى المدير', 'الي المدير').wer).toBe(0)
  })

  it('علامات الترقيم والنقاط تُتجاهل — مزوّد التفريغ يضيفها', () => {
    expect(werDetail('افتح الصفحة، ثم اضغط الحفظ.', 'افتح الصفحة ثم اضغط الحفظ').wer).toBe(0)
  })

  it('حذف كلمتين وإضافة واحدة من ثماني كلمات مرجع → 3/8', () => {
    const d = werDetail('كلمة كلمة كلمة كلمة كلمة كلمة كلمة كلمة', 'كلمة كلمة كلمة كلمة كلمة كلمة كلمةX')
    // 7 فرضية: 6 صحيحة + إبدال واحد؛ والثامنة محذوفة → (1+1+0)/8
    expect(d.sub).toBe(1)
    expect(d.del).toBe(1)
    expect(d.ins).toBe(0)
    expect(werDetail('كلمة كلمة كلمة كلمة كلمة كلمة كلمة كلمة', 'كلمة كلمة كلمة كلمة كلمة كلمة كلمةX').wer).toBeCloseTo(2 / 8, 10)
  })

  it('فرضية فارغة مقابل مرجع → 1 كامل', () => {
    expect(werDetail('ثلاث كلمات هنا', '').wer).toBe(1)
  })

  it('مرجع فارغ → 0 (لا شيء ليُخطأ فيه) والتفصيل أصفار', () => {
    expect(werDetail('', 'أي نص').wer).toBe(0)
    expect(werDetail('', 'نص').refWords).toBe(0)
  })

  it('الأرقام الشرقية تعادل الغربية — لا تُحتسب خطأ', () => {
    expect(werDetail('الفاتورة رقم ١٢٣', 'الفاتورة رقم 123').wer).toBe(0)
  })

  it('الترتيب المعكوس يُحتسب كما يجب: كل الكلمات إبدالات', () => {
    expect(werDetail('الرصيد الشهري', 'الشهري الرصيد').wer).toBeCloseTo(1, 10)
  })
})
