import { describe, expect, it } from 'vitest'
import { wer, werDetail } from './wer'

/** بوابة VOX-04: WER ‏≤20% — المنطق نقِي في core ليُعاد استخدامه على أدلة المالك الحقيقية */
describe('wer — نسبة أخطاء الكلمات', () => {
  it('نص مطابق تمامًا → صفر', () => {
    expect(wer('افتح صفحة الفواتير واضغط إنشاء', 'افتح صفحة الفواتير واضغط إنشاء')).toBe(0)
  })

  it('إبدال كلمة واحدة من عشر → 0.1', () => {
    expect(wer('واحد اثنان ثلاثة أربعة خمسة ستة سبعة ثمانية تسعة عشرة', 'واحد اثنان ثلاثة خمسة خمسة ستة سبعة ثمانية تسعة عشرة')).toBeCloseTo(0.1, 10)
  })

  it('التشكيل والهمزات وة/ه وى/ي لا تُحتسب أخطاء', () => {
    expect(wer('افتَح صَفحَة الفواتير', 'افتح صفحه الفواتير')).toBe(0)
    expect(wer('إلى المدير', 'الي المدير')).toBe(0)
  })

  it('علامات الترقيم والنقاط تُتجاهل — مزوّد التفريغ يضيفها', () => {
    expect(wer('افتح الصفحة، ثم اضغط الحفظ.', 'افتح الصفحة ثم اضغط الحفظ')).toBe(0)
  })

  it('حذف كلمتين وإضافة واحدة من ثماني كلمات مرجع → 3/8', () => {
    const d = werDetail('كلمة كلمة كلمة كلمة كلمة كلمة كلمة كلمة', 'كلمة كلمة كلمة كلمة كلمة كلمة كلمةX')
    // 7 فرضية: 6 صحيحة + إبدال واحد؛ والثامنة محذوفة → (1+1+0)/8
    expect(d.sub).toBe(1)
    expect(d.del).toBe(1)
    expect(d.ins).toBe(0)
    expect(wer('كلمة كلمة كلمة كلمة كلمة كلمة كلمة كلمة', 'كلمة كلمة كلمة كلمة كلمة كلمة كلمةX')).toBeCloseTo(2 / 8, 10)
  })

  it('فرضية فارغة مقابل مرجع → 1 كامل', () => {
    expect(wer('ثلاث كلمات هنا', '')).toBe(1)
  })

  it('مرجع فارغ → 0 (لا شيء ليُخطأ فيه) والتفصيل أصفار', () => {
    expect(wer('', 'أي نص')).toBe(0)
    expect(werDetail('', 'نص').refWords).toBe(0)
  })

  it('الأرقام الشرقية تعادل الغربية — لا تُحتسب خطأ', () => {
    expect(wer('الفاتورة رقم ١٢٣', 'الفاتورة رقم 123')).toBe(0)
  })

  it('الترتيب المعكوس يُحتسب كما يجب: كل الكلمات إبدالات', () => {
    expect(wer('الرصيد الشهري', 'الشهري الرصيد')).toBeCloseTo(1, 10)
  })
})
