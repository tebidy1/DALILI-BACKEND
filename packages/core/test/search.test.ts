import { describe, expect, it } from 'vitest'
import { normalizeFa, faIncludes, lightStem, normalizeForIndex, highlightSnippet } from '../src/search'

describe('normalizeFa — تطبيع البحث العربي', () => {
  it('يوحّد الهمزات والتاء المربوطة والألف المقصورة', () => {
    expect(normalizeFa('أحمد إبراهيم آمنة شقيقة عيسى')).toBe('احمد ابراهيم امنه شقيقه عيسي')
  })

  it('يزيل التشكيل والتطويل', () => {
    expect(normalizeFa('مُدَرَّســـة')).toBe('مدرسه')
  })

  it('يحوّل الأرقام الشرقية إلى غربية ويصغّر اللاتينية', () => {
    expect(normalizeFa('١٢٣ ABC')).toBe('123 abc')
  })

  it('faIncludes يجد رغم الاختلافات', () => {
    expect(faIncludes('تقرير المبيعات الشهري', 'المبيعات')).toBe(true)
    expect(faIncludes('المستشفى المركزي', 'المستشفي')).toBe(true) // ى تُوحد مع ي
    expect(faIncludes('مدرسة الرياض', 'مدرسه')).toBe(true) // ة تُوحد مع ه
    expect(faIncludes('Tango Workflow', 'tango')).toBe(true)
    expect(faIncludes('الفواتير', 'المخزون')).toBe(false)
  })

  it('إبرة فارغة تطابق دائمًا', () => {
    expect(faIncludes('أي شيء', '')).toBe(true)
  })
})

describe('lightStem — تجريد السوابق الخفيف (ب4)', () => {
  it('«ال» تُجرَّد إن بقي ≥3 محارف: الفاتورة → فاتوره', () => {
    expect(lightStem('الفاتوره')).toBe('فاتوره')
  })
  it('السوابق المركبة: وبالفاتورة → فاتوره', () => {
    expect(lightStem('وبالفاتوره')).toBe('فاتوره')
  })
  it('حرف واحد يُجرَّد فقط إن بقي ≥4: وفاتوره → فاتوره، ووحدة تبقى', () => {
    expect(lightStem('وفاتوره')).toBe('فاتوره')
    expect(lightStem('وحد')).toBe('وحد')
    expect(lightStem('ولد')).toBe('ولد')
  })
  it('كلمات قصيرة محمية من التجريد الجائر: الله، الذي، وكالة الجزء الأول', () => {
    expect(lightStem('التي')).toBe('التي') // بقي 1 < 3
    expect(lightStem('لل')).toBe('لل') // بقي 0
  })
  it('لا تُجرَّد لواحق أبدًا: فاتورات تبقى فاتورات', () => {
    expect(lightStem('فاتورات')).toBe('فاتورات')
  })
})

describe('normalizeForIndex — تطبيع الفهرسة الكامل', () => {
  it('الهمزات والتشكيل مع تجريد السوابق معًا: إعتماد → اعتماد (ب3)', () => {
    expect(normalizeForIndex('إعتماد')).toBe('اعتماد')
  })
  it('المطابقة المتبادلة: «الفاتورة» و«فاتورة» يتطابقان (ب4)', () => {
    expect(normalizeForIndex('الفاتورة')).toBe(normalizeForIndex('فاتورة'))
  })
})

