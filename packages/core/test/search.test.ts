describe('highlightSnippet — المقتطف المظلل', () => {
  it('يظلل المطابقة عبر الاختلافات: «الفاتوره» تجد «الفاتورة» في النص', () => {
    const out = highlightSnippet('صدرت الفاتورة الضريبية من فرع جدة اليوم', 'الفاتوره')
    expect(out).toContain('<mark>الفاتورة</mark>')
  })
  it('يظلل عبر التجريد: استعلام «فاتورة» يظلل «وبالفاتورة»', () => {
    const out = highlightSnippet('راجع وبالفاتورة المرفقة كشف الحساب', 'فاتورة')
    expect(out).toContain('<mark>وبالفاتورة</mark>')
  })
  it('يهرب HTML الخام — لا حقن', () => {
    const out = highlightSnippet('وسم <script>alert(1)</script> فاتورة', 'فاتورة')
    expect(out).not.toContain('<script>')
    expect(out).toContain('&lt;script&gt;')
  })
  it('بلا مطابقة: يعرض البداية مهروبة بلا mark', () => {
    const out = highlightSnippet('نص لا علاقة له بالاستعلام', 'فاتورة')
    expect(out).not.toContain('<mark>')
  })
  it('يقصّ النص الطويل حول أول مطابقة بعلامة قطع', () => {
    const long = Array.from({ length: 60 }, (_, i) => `كلمة${i}`).join(' ') + ' فاتورة'
    const out = highlightSnippet(long, 'فاتورة', 10)
    expect(out).toContain('…')
    expect(out).toContain('<mark>فاتورة</mark>')
  })
})
